async function main() {
  console.log(`\nAdding ${SUPPLIERS.length} suppliers to contacts...\n`);

  const col = db.collection('contacts');
  let batch = db.batch();
  let count = 0;

  for (const name of SUPPLIERS) {
    const id = 'sup-' + name.toLowerCase().replace(/[^a-z0-9]/g, '-').replace(/-+/g, '-').substring(0, 40);
    batch.set(col.doc(id), {
      id,
      name,
      tipo:   'proveedor',
      type:   'Proveedor',
      activo: true,
      phone:  '',
      email:  '',
      address: '',
      tags:   ['proveedor'],
      givenName: name,
      paterno: '',
    });
    count++;
    if (count >= 400) {
      await batch.commit();
      batch = db.batch();
      count = 0;
    }
  }
  if (count > 0) await batch.commit();

  console.log(`✅  ${SUPPLIERS.length} proveedores escritos en contacts.\n`);
}

main().catch(e => { console.error('❌', e.message); process.exit(1); });
