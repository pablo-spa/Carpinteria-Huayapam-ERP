async function main() {
  console.log(`\nAdding ${CLIENTS.length} clients to contacts...\n`);

  const col = db.collection('contacts');
  let batch = db.batch();
  let count = 0;

  for (const name of CLIENTS) {
    const id = 'cli-' + name.toLowerCase().replace(/[^a-z0-9]/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '').substring(0, 40);
    batch.set(col.doc(id), {
      id,
      name,
      tipo: 'cliente',
      activo: true,
      phone: '',
      email: '',
      address: '',
      givenName: name,
      paterno: '',
    });
    count++;
    if (count >= 400) {
      await batch.commit();
      batch = db.batch();
      count = 0;
    }
  }
  if (count > 0) await batch.commit();

  console.log(`✅  ${CLIENTS.length} clientes escritos en contacts.\n`);
}

main().catch(e => { console.error('❌', e.message); process.exit(1); });
